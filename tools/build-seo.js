/*
 * build-seo.js — pre-render docsify pages into crawlable, 200-status HTML.
 *
 * Physical HTML pages provide direct document URLs on GitHub Pages and readable
 * content without JavaScript, alongside the interactive Docsify application.
 *
 * This script:
 *   1. Renders every docs/<name>.md (except README and _sidebar) to docs/<name>.html
 *      with proper <title>, <meta description>, canonical, OpenGraph, and styled body.
 *   2. Injects the rendered README into index.html's #app (between SEO markers) so the
 *      homepage also serves real content/links to crawlers; docsify replaces it at runtime.
 *   3. Writes sitemap.xml and robots.txt.
 *
 * Re-run after editing any .md:  node tools/build-seo.js
 */
const fs = require('fs');
const path = require('path');
const { marked } = require('./marked.min.js');

const DOCS = path.join(__dirname, '..', 'docs');
const BASE = 'https://cizentech.github.io/support/';
const SITE = 'CIZEN TECH · Technical Support';
const EXCLUDE = new Set(['_sidebar.md', 'README.md']);

// --- helpers ---------------------------------------------------------------

const stripTags = (s) => s.replace(/<[^>]+>/g, '');
const decode = (s) => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<')
  .replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'");
const escAttr = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;')
  .replace(/</g, '&lt;').replace(/>/g, '>');

function rewriteLinks(html) {
  // docsify route -> static page:  href="#/Page" / "#/Page?id=x" -> "Page.html"
  html = html.replace(/href="#\/([^"?#]*)(?:\?([^"#]*))?(?:#([^"]*))?"/g, (_, name, query, fragment) => {
    const id = new URLSearchParams(decode(query || '')).get('id') || fragment;
    return `href="${!name || name === 'README' ? 'index' : name}.html${id ? '#' + escAttr(id) : ''}"`;
  });
  // markdown page link:  href="Page.md" / "./Page.md" -> "Page.html"
  html = html.replace(/href="\.?\/?([^":]+?)\.md(#[^"]*)?"/g, 'href="$1.html$2"');
  return html.replace(/href="README.html/g, 'href="index.html');
}

function render(md) {
  const counts = new Map();
  return rewriteLinks(marked.parse(md)).replace(/<h([1-6])>([\s\S]*?)<\/h\1>/g, (_, level, title) => {
    const base = decode(stripTags(title)).trim().toLowerCase()
      .replace(/[\u2000-\u206F\u2E00-\u2E7F\\'!"#$%&()*+,./:;<=>?@[\]^`{|}~]/g, '')
      .replace(/\s/g, '-').replace(/-+/g, '-').replace(/^(\d)/, '_$1');
    const count = counts.get(base) || 0;
    counts.set(base, count + 1);
    return `<h${level} id="${escAttr(base + (count ? '-' + count : ''))}">${title}</h${level}>`;
  });
}

function titleOf(md, fallback) {
  const m = md.match(/^\s*#\s+(.+?)\s*$/m);
  return m ? decode(stripTags(m[1])).trim() : fallback;
}

function descOf(md) {
  // first reasonably long plain-text paragraph
  const blocks = md.split(/\n\s*\n/);
  for (const b of blocks) {
    const t = decode(stripTags(b))
      .replace(/\\([\\`*_{}\[\]()#+.!~>-])/g, '$1') // markdown escapes
      .replace(/[`*_]/g, '')      // emphasis / code markers
      .replace(/^[\s>#*-]+/, '')  // leading blockquote / heading / list markers
      .replace(/\|/g, ' ')        // table pipes
      .replace(/\s+/g, ' ').trim();
    if (t.length >= 40 && !/^!\[/.test(b)) return t.slice(0, 157).trim() + (t.length > 157 ? '…' : '');
  }
  return 'CIZEN TECH MIG Series frame grabber and CameraMaster documentation.';
}

function page(name, title, desc, bodyHtml) {
  const canonical = BASE + name + '.html';
  const headings = [...bodyHtml.matchAll(/<h2 id="([^"]+)">([\s\S]*?)<\/h2>/g)];
  const toc = headings.length ? `<details class="doc-toc"><summary>On this page</summary><ul>${headings.map(h => `<li><a href="#${h[1]}">${h[2]}</a></li>`).join('')}</ul></details>` : '';
  return `<!DOCTYPE html>
<!-- Generated by tools/build-seo.js; edit the Markdown source. -->
<html lang="${name === 'SFR' ? 'ko' : 'en'}">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${escAttr(title)} · CIZEN TECH</title>
  <meta name="description" content="${escAttr(desc)}">
  <link rel="canonical" href="${canonical}">
  <meta property="og:type" content="article">
  <meta property="og:title" content="${escAttr(title)}">
  <meta property="og:description" content="${escAttr(desc)}">
  <meta property="og:url" content="${canonical}">
  <link rel="icon" type="image/png" sizes="32x32" href="img/cizentech-32x32.png">
  <link rel="stylesheet" href="doc.css">
</head>
<body>
  <a class="skip-link" href="#main">Skip to content</a>
  <header class="doc-top">
    <a class="brand" href="index.html"><img src="img/cizentech-32x32.png" alt="" width="24" height="24">CIZEN TECH <span>/ Support</span></a>
    <nav aria-label="Documentation"><a href="Downloads.html">Downloads</a><a href="index.html#/${name}">Search &amp; browse</a><button class="theme-toggle" type="button" aria-label="Switch color theme">Dark</button></nav>
  </header>
  <script src="portal.js"></script>
  <script src="navigation.js"></script>
  <main class="markdown-section" id="main" tabindex="-1">
${toc}
${bodyHtml}
    <hr><p>Need help? <a href="Troubleshooting.html">Troubleshooting</a> · <a href="Technical_Support.html">Contact technical support</a></p>
  </main>
  <footer class="doc-foot">
    <strong>CIZEN TECH Co., Ltd.</strong> · <a href="https://www.cizentech.com/">Company</a> · Technical support: <a href="mailto:sw@cizentech.com">sw@cizentech.com</a>
  </footer>
</body>
</html>
`;
}

// --- build pages -----------------------------------------------------------

const mdFiles = fs.readdirSync(DOCS)
  .filter((f) => f.endsWith('.md') && !EXCLUDE.has(f));

// Omit filesystem mtimes: a fresh clone changes them without changing content.
const urls = [{ loc: BASE }];

for (const file of fs.readdirSync(DOCS).filter(f => f.endsWith('.html') && f !== 'index.html')) {
  if (!mdFiles.includes(file.replace(/\.html$/, '.md')) &&
      fs.readFileSync(path.join(DOCS, file), 'utf8').includes('Generated by tools/build-seo.js')) {
    fs.unlinkSync(path.join(DOCS, file));
  }
}

for (const file of mdFiles) {
  const name = file.replace(/\.md$/, '');
  const md = fs.readFileSync(path.join(DOCS, file), 'utf8');
  const title = titleOf(md, name);
  const desc = descOf(md);
  const body = render(md);
  fs.writeFileSync(path.join(DOCS, name + '.html'), page(name, title, desc, body));
  urls.push({ loc: BASE + name + '.html' });
  console.log('  page  ->', name + '.html');
}

// --- inject homepage content into index.html #app --------------------------

const idxPath = path.join(DOCS, 'index.html');
let idx = fs.readFileSync(idxPath, 'utf8');
const home = render(fs.readFileSync(path.join(DOCS, 'README.md'), 'utf8'));
const block = `<!--SEO:HOME:START-->\n<main id="main" class="markdown-section" tabindex="-1">\n${home}\n</main>\n<!--SEO:HOME:END-->`;
if (/<!--SEO:HOME:START-->[\s\S]*?<!--SEO:HOME:END-->/.test(idx)) {
  idx = idx.replace(/<!--SEO:HOME:START-->[\s\S]*?<!--SEO:HOME:END-->/, block);
} else {
  idx = idx.replace(/<div id="app">[\s\S]*?<\/div>/, `<div id="app">\n${block}\n</div>`);
}
fs.writeFileSync(idxPath, idx);
console.log('  inject-> index.html #app (homepage content)');

// --- sitemap.xml + robots.txt ----------------------------------------------

const iso = (d) => d.toISOString().slice(0, 10);
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${u.loc}</loc></url>`).join('\n')}
</urlset>
`;
fs.writeFileSync(path.join(DOCS, 'sitemap.xml'), sitemap);

fs.writeFileSync(path.join(DOCS, 'robots.txt'),
  `User-agent: *\nAllow: /\n\nSitemap: ${BASE}sitemap.xml\n`);

console.log('  write -> sitemap.xml, robots.txt');
console.log('Done.', urls.length, 'URLs.');
